// The ends of an Alt-drag that leave no copy, and the Alt-drags that copy nothing, in the whole
// editor opened in Node.
import { describe, expect, it } from 'vitest'

import { openSession } from '@dazbee/doc'
import { anotherTab } from '@dazbee/doc/test-store'
import type { DesignInput } from '@dazbee/schema'

import { DESIGN, FLOW } from '../../test-actions.ts'
import { openAltDrag as open } from './test-alt-drag.ts'

describe('Alt-drag', () => {
  describe('leaves no copy', () => {
    it('Escape drops the drag: no copy, no undo step, the selection the press found', async () => {
      const { editor, core, mouse, keys, at, go, made, unchanged } = await open()
      mouse.click(at(300, 350).x, at(300, 350).y)
      expect(core.selection()).toEqual(['b'])
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      go(300, 150)
      expect(made()).toHaveLength(1)
      keys.down('Escape')
      unchanged()
      expect(core.canUndo()).toBe(false)
      expect(core.selection()).toEqual(['b'])
      mouse.up()
      keys.up('Escape')
      keys.up('Alt')
      unchanged()
      editor.end()
    })

    it('released where the original is, after 5 px inside the snap, or 150 out and back: no copy, nothing to undo, the original selected', async () => {
      const { editor, core, mouse, keys, at, go, made, unchanged } = await open()
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      mouse.move(at(150, 150).x + 5, at(150, 150).y)
      expect(made()).toHaveLength(1)
      mouse.up()
      unchanged()
      expect(core.canUndo()).toBe(false)
      expect(core.selection()).toEqual(['a'])
      mouse.down()
      go(300, 150)
      expect(made()).toHaveLength(1)
      go(150, 150)
      mouse.up()
      keys.up('Alt')
      unchanged()
      expect(core.canUndo()).toBe(false)
      expect(core.selection()).toEqual(['a'])
      editor.end()
    })

    it('an empty Alt-drag from a layer not selected leaves it selected, as a click does', async () => {
      const { editor, core, mouse, keys, at, go, made, unchanged } = await open()
      mouse.click(at(300, 350).x, at(300, 350).y)
      expect(core.selection()).toEqual(['b'])
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      mouse.move(at(150, 150).x + 5, at(150, 150).y)
      expect(made()).toHaveLength(1)
      mouse.up()
      keys.up('Alt')
      unchanged()
      expect(core.canUndo()).toBe(false)
      expect(core.selection()).toEqual(['a'])
      editor.end()
    })

    it('a copy 1 px off its original stays, with snapping off', async () => {
      const { editor, core, mouse, keys, at, go, made } = await open()
      core.setSnapping(false)
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      mouse.move(at(150, 150).x + 30, at(150, 150).y)
      go(151, 150)
      mouse.up()
      keys.up('Alt')
      expect(made()).toHaveLength(1)
      expect(core.boxOf(made()[0] ?? '')).toMatchObject({ x: 101, y: 100 })
      expect(core.undoName()).toBe('duplicate')
      editor.end()
    })

    it('the window losing the focus lets go of Alt: a move again', async () => {
      const { editor, core, mouse, keys, go, made } = await open()
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      go(300, 150)
      expect(made()).toHaveLength(1)
      core.input.blur()
      core.redraw()
      expect(made()).toEqual([])
      expect(core.boxOf('a')).toMatchObject({ x: 250, y: 100 })
      // Let go while the window had no focus: the release no longer carries Alt.
      keys.up('Alt')
      mouse.up()
      expect(core.undoName()).toBe('move')
      editor.end()
    })

    it('undo mid-drag ends it and takes the copy away', async () => {
      const { editor, core, mouse, keys, go, made, unchanged } = await open()
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      go(300, 150)
      expect(made()).toHaveLength(1)
      core.perform('undo')
      core.redraw()
      unchanged()
      expect(core.selection()).toEqual([])
      go(320, 150)
      mouse.up()
      keys.up('Alt')
      unchanged()
      editor.end()
    })

    it('undo mid-drag with the copies back on their originals takes them away and leaves the step before the drag', async () => {
      const { editor, core, mouse, keys, at, go, made } = await open()
      mouse.drag(at(300, 350), at(300, 450))
      expect(core.boxOf('b')).toMatchObject({ y: 400 })
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      go(300, 150)
      go(150, 150)
      core.perform('undo')
      core.redraw()
      expect(made()).toEqual([])
      expect(core.boxOf('b')).toMatchObject({ y: 400 })
      expect(core.boxOf('a')).toMatchObject({ x: 100, y: 100 })
      mouse.up()
      keys.up('Alt')
      editor.end()
    })

    it('a layer locked against deleting: its copy refuses a delete, and letting go of Alt takes it away all the same', async () => {
      const locked = { ...DESIGN, nodes: { ...DESIGN.nodes, a: { ...DESIGN.nodes.a, lock: { delete: true } } } }
      const { editor, core, mouse, keys, go, made, unchanged } = await open(locked as DesignInput)
      keys.down('Alt')
      go(150, 150)
      mouse.down()
      go(300, 150)
      const [copy = ''] = made()
      expect(core.design().nodes[copy]?.lock).toMatchObject({ delete: true })
      expect(() => core.session.run('node.delete', { ids: [copy] })).toThrow(/locked/)
      keys.up('Alt')
      expect(made()).toEqual([])
      mouse.up()
      expect(core.boxOf('a')).toMatchObject({ x: 250, y: 100 })
      core.perform('undo')
      unchanged()
      editor.end()
    })

    it('a layer another tab deletes mid-drag is left out; with every one gone it stays a move', async () => {
      const { editor, core, mouse, keys, go, made } = await open()
      // Another tab deletes them, and the change reaches the editor's store.
      const elsewhere = (ids: string[]) => {
        const other = anotherTab(core.store)
        openSession(other.store).run('node.delete', { ids })
        other.deliver()
        core.redraw()
      }
      core.select(['a', 'b'])
      core.redraw()
      go(150, 150)
      mouse.down()
      go(300, 150)
      elsewhere(['b'])
      keys.down('Alt')
      expect(made()).toHaveLength(1)
      expect(core.boxOf('a')).toMatchObject({ x: 100, y: 100 })
      keys.up('Alt')
      expect(made()).toEqual([])
      elsewhere(['a'])
      keys.down('Alt')
      go(320, 150)
      expect(made()).toEqual([])
      mouse.up()
      keys.up('Alt')
      editor.end()
    })
  })

  describe('copies nothing', () => {
    it('with no free layer selected: the selection stays', async () => {
      const { editor, core, mouse, keys, at, made } = await open(FLOW)
      core.pickLayer({ id: 'inRow', frameId: 'sq' })
      core.redraw()
      core.toggleSelected('fixed')
      core.redraw()
      const picked = core.selection()
      keys.down('Alt')
      mouse.drag(at(125, 525), at(400, 300))
      keys.up('Alt')
      expect(made()).toEqual([])
      expect(core.selection()).toEqual(picked)
      editor.end()
    })

    it('of a layer a flow places among free ones: the free one alone is copied', async () => {
      const { editor, core, mouse, keys, at, made } = await open(FLOW)
      core.pickLayer({ id: 'fixed', frameId: 'sq' })
      core.redraw()
      core.toggleSelected('a')
      core.redraw()
      keys.down('Alt')
      mouse.drag(at(150, 150), at(450, 250))
      keys.up('Alt')
      const [copy = ''] = made()
      expect(made()).toHaveLength(1)
      expect(core.design().nodes[copy]?.parentId).toBe('sq')
      expect(core.boxOf(copy)).toMatchObject({ x: 400, y: 200 })
      editor.end()
    })

    it('from a layer locked in place, or empty space: a marquee', async () => {
      const { editor, core, mouse, keys, at, go, made, unchanged } = await open()
      keys.down('Alt')
      go(725, 725)
      mouse.down()
      go(800, 800)
      expect(editor.modules.pointer.gesture()?.kind).toBe('marquee')
      mouse.up()
      mouse.drag(at(560, 560), at(620, 620))
      keys.up('Alt')
      expect(made()).toEqual([])
      unchanged()
      expect(core.canUndo()).toBe(false)
      editor.end()
    })

    it('on a handle: Alt resizes from the centre and copies nothing', async () => {
      const { editor, core, mouse, keys, at, made } = await open()
      mouse.click(at(150, 150).x, at(150, 150).y)
      const corner = editor.at('se') as { x: number; y: number }
      keys.down('Alt')
      mouse.drag(corner, { x: corner.x + 30, y: corner.y + 30 })
      keys.up('Alt')
      expect(made()).toEqual([])
      const box = core.boxOf('a')
      expect(box && box.x + box.width / 2).toBeCloseTo(150)
      expect(box?.width).toBeGreaterThan(100)
      expect(core.undoName()).not.toBe('duplicate')
      editor.end()
    })
  })
})
